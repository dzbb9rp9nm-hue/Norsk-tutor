// Publish only the app, never project notes, tests, credentials, or database scripts.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true });
for (const name of ['index.html', 'app.js', 'password-reset.js', 'learning.js', 'sync.js', 'call-mode.js', 'native-speech.js', 'privacy.html', 'audio-lessons.js', 'audio-player.js', 'styles.css', 'scenarios.js', 'tutor-prompt.js', '_headers']) {
  fs.copyFileSync(path.join(root, name), path.join(output, name));
}
console.log('Prepared fourteen app files for publication.');

// Generate the streaming tutor edge function. The edge runtime loads plain ES modules and
// cannot read the shared prompt files, which are browser-style scripts with a CommonJS
// fallback. So each shared file is wrapped in a function that provides the `module` (and,
// for prompt.cjs, `require`) it expects, and the handler source from server/tutor-stream.mjs
// is appended with its `export` keywords removed. No code is evaluated at build time.
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const wrap = (name, source, requires) => 'const ' + name + '=(()=>{const module={exports:{}};'
  + (requires ? 'const require=(p)=>p.endsWith("tutor-prompt.js")?__tutorPrompt:__scenarios;' : '')
  + '\n' + source + '\nreturn module.exports;})();';
const handler = read('server/tutor-stream.mjs');
if (!handler.includes('export function createTutorStream') || !handler.includes('export function validTutor')) {
  throw new Error('server/tutor-stream.mjs no longer matches what this generator expects.');
}
const generated = [
  '// GENERATED by scripts/build.cjs from server/tutor-stream.mjs and the shared prompt files.',
  '// Do not edit: change the sources and rebuild.',
  wrap('__tutorPrompt', read('tutor-prompt.js')),
  wrap('__scenarios', read('scenarios.js')),
  wrap('__systemPrompt', read('server/prompt.cjs'), true),
  handler.replace(/^export function /gm, 'function '),
  'export default createTutorStream({tutorPrompt:__tutorPrompt,scenarios:__scenarios,systemPrompt:__systemPrompt},(n)=>Netlify.env.get(n));',
  'export const config={path:"/api/account/tutor-stream"};',
  ''
].join('\n');
const edgeDir = path.join(root, 'netlify', 'edge-functions');
fs.mkdirSync(edgeDir, { recursive: true });
fs.writeFileSync(path.join(edgeDir, 'tutor-stream.mjs'), generated);
console.log('Generated the streaming tutor edge function.');
